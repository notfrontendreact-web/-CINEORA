export type TranslationKey = keyof typeof translations.en;

export function t(locale: Locale, key: TranslationKey): string {
  return translations[locale][key] || translations.en[key] || key;
}

export function getDirection(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'fa' ? 'rtl' : 'ltr';
}

export function getBilingual(value: { fa: string; en: string } | null | undefined, locale: Locale): string {
  if (!value) return '';
  return value[locale] || value.en || value.fa || '';
}

export function formatPrice(price: number, locale: Locale, currency: string = 'USD'): string {
  if (locale === 'fa') {
    return new Intl.NumberFormat('fa-IR').format(Math.round(price * 60000)) + ' تومان';
  }
  return '$' + price.toFixed(2);
}
